DECLARE
    target regclass;
BEGIN
    FOREACH target IN ARRAY ARRAY[
        'core.venture'::regclass,
        'core.venture_qualification'::regclass,
        'nlp.venture_intent_set'::regclass,
        'social.contact_record'::regclass,
