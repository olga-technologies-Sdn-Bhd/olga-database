            SELECT 1 FROM pg_trigger
            WHERE tgrelid = target AND tgname = 'set_row_version' AND tgenabled <> 'D'
        ) THEN
            RAISE EXCEPTION 'SCI row-version trigger is missing for %.', target;
        END IF;
    END LOOP;

